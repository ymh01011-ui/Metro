package code.name.monkey.retromusic.util

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import code.name.monkey.retromusic.R
import code.name.monkey.retromusic.model.Song
import code.name.monkey.retromusic.util.MergedImageUtils.joinImages
import code.name.monkey.retromusic.util.MusicUtil.getMediaStoreAlbumCoverUri
import com.bumptech.glide.Glide
import com.bumptech.glide.load.resource.bitmap.RoundedCorners

object AutoGeneratedPlaylistBitmap {

    // size = حجم الصورة النهائية بالبكسل. القايمة الصغيرة بتطلب حجم صغير (أسرع وأخف في الذاكرة)
    // والهيدر الكبير بيطلب حجم كبير.
    fun getBitmap(
        context: Context, songPlaylist: List<Song>?, size: Int = 1200
    ): Bitmap? {
        if (songPlaylist == null || songPlaylist.isEmpty()) return getDefaultBitmap(context)
        if (songPlaylist.size == 1) {
            return getBitmapWithAlbumId(context, songPlaylist[0].albumId, size, rounded = true)
        }
        val albumID: MutableList<Long> = ArrayList()
        for (song in songPlaylist) {
            if (!albumID.contains(song.albumId)) albumID.add(song.albumId)
        }
        val tilePx = MergedImageUtils.tileSizeFor(size)
        val art: MutableList<Bitmap> = ArrayList()
        for (id in albumID) {
            val bitmap = getBitmapWithAlbumId(context, id, tilePx, rounded = false)
            if (bitmap != null) art.add(bitmap)
            if (art.size == 9) break
        }
        if (art.isEmpty()) return getDefaultBitmap(context)
        return joinImages(art, size)
    }

    private fun getBitmapWithAlbumId(
        context: Context, id: Long, sizePx: Int, rounded: Boolean
    ): Bitmap? {
        return try {
            var request = Glide.with(context).asBitmap()
            // الحواف الدائرية في الصورة المجمّعة بترسم بعد التجميع، فمش بنقصّ هنا
            if (rounded) request = request.transform(RoundedCorners(20))
            request
                .load(getMediaStoreAlbumCoverUri(id))
                .submit(sizePx, sizePx)
                .get()
        } catch (e: Exception) {
            null
        }
    }

    private fun getDefaultBitmap(context: Context): Bitmap {
        return BitmapFactory.decodeResource(context.resources, R.drawable.default_album_art)
    }
}

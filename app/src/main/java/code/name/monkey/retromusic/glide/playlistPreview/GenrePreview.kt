package code.name.monkey.retromusic.glide.playlistPreview

import android.content.Context
import android.graphics.Bitmap
import code.name.monkey.retromusic.model.Genre
import code.name.monkey.retromusic.model.Song
import code.name.monkey.retromusic.util.AutoGeneratedPlaylistBitmap
import com.bumptech.glide.Priority
import com.bumptech.glide.load.DataSource
import com.bumptech.glide.load.Options
import com.bumptech.glide.load.data.DataFetcher
import com.bumptech.glide.load.model.ModelLoader
import com.bumptech.glide.load.model.ModelLoader.LoadData
import com.bumptech.glide.load.model.ModelLoaderFactory
import com.bumptech.glide.load.model.MultiModelLoaderFactory
import com.bumptech.glide.signature.ObjectKey
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch

// نفس PlaylistPreview بالظبط بس للـ genre: نفس مولّد الصورة (AutoGeneratedPlaylistBitmap)
class GenrePreview(val genre: Genre, val songs: List<Song>) {

    // بتتحسب مرة واحدة: بتتغير لو محتوى الـ genre اتغير (مش بس عدد الأغاني)
    private val songsSignature: Int by lazy {
        songs.fold(songs.size) { acc, s -> 31 * acc + s.id.hashCode() }
    }

    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (javaClass != other?.javaClass) return false

        other as GenrePreview
        if (other.genre.id != genre.id) return false
        if (other.songsSignature != songsSignature) return false
        return true
    }

    override fun hashCode(): Int {
        return 31 * genre.id.hashCode() + songsSignature
    }
}

class GenrePreviewFetcher(
    val context: Context,
    private val genrePreview: GenrePreview,
    private val width: Int = 0,
    private val height: Int = 0
) : DataFetcher<Bitmap>, CoroutineScope by GlideScope() {
    override fun loadData(priority: Priority, callback: DataFetcher.DataCallback<in Bitmap>) {
        launch {
            try {
                val bitmap = AutoGeneratedPlaylistBitmap.getBitmap(
                    context,
                    genrePreview.songs,
                    // حجم الصورة بيتحدد من حجم الـ View، زي الـ Playlist
                    if (width > 0 && height > 0) maxOf(width, height) else 1200
                )
                callback.onDataReady(bitmap)
            } catch (e: Exception) {
                callback.onLoadFailed(e)
            }
        }
    }

    override fun cleanup() {}

    override fun cancel() {
        cancel(null)
    }

    override fun getDataClass(): Class<Bitmap> {
        return Bitmap::class.java
    }

    override fun getDataSource(): DataSource {
        return DataSource.LOCAL
    }
}

class GenrePreviewLoader(val context: Context) : ModelLoader<GenrePreview, Bitmap> {
    override fun buildLoadData(
        model: GenrePreview,
        width: Int,
        height: Int,
        options: Options
    ): LoadData<Bitmap> {
        return LoadData(
            ObjectKey(model),
            GenrePreviewFetcher(context, model, width, height)
        )
    }

    override fun handles(model: GenrePreview): Boolean {
        return true
    }

    class Factory(val context: Context) : ModelLoaderFactory<GenrePreview, Bitmap> {
        override fun build(multiFactory: MultiModelLoaderFactory): ModelLoader<GenrePreview, Bitmap> {
            return GenrePreviewLoader(context)
        }

        override fun teardown() {}
    }
}
